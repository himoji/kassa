/** @jest-environment node */
import { afterEach, beforeEach, describe, expect, it } from "@jest/globals";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import {
  ARCHITECTURE_MD,
  buildGraph,
  checkGraph,
  GRAPH_JSON,
  parseProviders,
  renderArchitecture,
  renderMermaid,
  routeFromFile,
  validateGraph,
  writeGraph,
  type Graph,
} from "../lib/graph";

const PROVIDERS = `import type { ReactNode } from "react";

import { QueryProvider } from "@/lib/query";
import { ThemeProvider as UiThemeProvider, ToastHost } from "@/components/ui";

/** Generated by \`bun setup\`; mentions <NotAProvider> in prose. */
export function Providers({ children }: { children: ReactNode }) {
  return (
    <QueryProvider>
      <UiThemeProvider>
        {children}
        <ToastHost />
      </UiThemeProvider>
    </QueryProvider>
  );
}
`;

const ENV_TS = `/** Generated. Never read them dynamically: \`process.env.EXPO_PUBLIC_X\`. */
import { z } from "zod";

const raw = {
  APP_VARIANT: optional(process.env.EXPO_PUBLIC_APP_VARIANT),
  API_URL: optional(process.env.EXPO_PUBLIC_API_URL),
};
`;

const FILES: Record<string, string> = {
  ".readynative.json": JSON.stringify({
    version: 1,
    preset: "default",
    selection: { ui: "nativewind5", data: "react-query", auth: "none", payments: "" },
    applied: true,
    modules: {
      app: { expo: {} },
      postSetup: [],
      doctor: [
        {
          type: "env",
          module: "react-query",
          keys: ["EXPO_PUBLIC_API_URL", "API_SECRET"],
          guide: "https://readynative.app/docs/features/data/react-query",
        },
      ],
    },
    keepModules: false,
    examples: false,
  }),
  "src/providers.tsx": PROVIDERS,
  "src/lib/env.ts": ENV_TS,
  "src/lib/query.tsx": `export const QueryProvider = 1;\n`,
  "src/lib/api/client.ts": `import { env } from "@/lib/env";

export const url = env.API_URL;
`,
  "src/app/_layout.tsx": `import { Providers } from "@/providers";\n`,
  "src/app/(tabs)/_layout.tsx": `export default function TabsLayout() {}\n`,
  "src/app/(tabs)/index.tsx": `import { HomeScreen } from "@/screens/home/home-screen";

export default HomeScreen;
`,
  "src/app/entry/[id].tsx": `export default function Entry() {}\n`,
  "src/app/api/hello+api.ts": `export function GET() {}\n`,
  "src/app/_catalog.tsx": `export default function Catalog() {}\n`,
  "src/screens/home/home-screen.tsx": `import { url } from "@/lib/api/client";

// @graph node=custom:sync kind=feature label="Background sync" edges=lib:api/client
export function HomeScreen() {
  return url;
}
`,
  "src/hooks/use-thing.ts": `import { useStore } from "@/stores/thing";\n`,
  "src/stores/thing.ts": `export const useStore = 1;\n`,
  "src/screens/__tests__/home-screen.test.tsx": `import "@/lib/env";\n`,
  "docs/graph.extra.json": JSON.stringify({
    nodes: [{ id: "service:stripe", kind: "service", label: "Stripe" }],
    edges: [
      { from: "service:stripe", to: "env:EXPO_PUBLIC_API_URL", kind: "reads" },
      { from: "service:stripe", to: "nope:missing", kind: "custom" },
    ],
  }),
};

function createTree(): string {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "readynative-graph-"));
  for (const [rel, content] of Object.entries(FILES)) {
    const abs = path.join(root, rel);
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
  }
  return root;
}

const ids = (graph: Graph) => graph.nodes.map((n) => n.id);
const has = (graph: Graph, from: string, kind: string, to: string) =>
  graph.edges.some((e) => e.from === from && e.kind === kind && e.to === to);

describe("routeFromFile", () => {
  it("maps expo-router files onto route paths", () => {
    expect(routeFromFile("src/app/(tabs)/index.tsx")?.id).toBe("route:/");
    expect(routeFromFile("src/app/(tabs)/explore.tsx")?.id).toBe("route:/explore");
    expect(routeFromFile("src/app/entry/[id].tsx")?.id).toBe("route:/entry/[id]");
    expect(routeFromFile("src/app/+not-found.tsx")?.id).toBe("route:/+not-found");
  });

  it("keeps the real path in a layout id, so groups do not collide", () => {
    expect(routeFromFile("src/app/_layout.tsx")?.id).toBe("route:_layout");
    expect(routeFromFile("src/app/(tabs)/_layout.tsx")?.id).toBe("route:(tabs)/_layout");
    expect(routeFromFile("src/app/(tabs)/_layout.tsx")?.type).toBe("layout");
  });

  it("marks +api files and ignores private files", () => {
    expect(routeFromFile("src/app/api/hello+api.ts")).toEqual({
      id: "route:/api/hello",
      label: "/api/hello",
      file: "src/app/api/hello+api.ts",
      type: "api",
    });
    expect(routeFromFile("src/app/_catalog.tsx")).toBeUndefined();
  });
});

describe("parseProviders", () => {
  it("reads the composition order out of the JSX, not the import list", () => {
    expect(parseProviders(PROVIDERS).map((p) => p.name)).toEqual([
      "QueryProvider",
      "UiThemeProvider",
      "ToastHost",
    ]);
    expect(parseProviders(PROVIDERS)[1].from).toBe("@/components/ui");
  });
});

describe("buildGraph", () => {
  let root: string;
  let graph: Graph;

  beforeEach(() => {
    root = createTree();
    graph = buildGraph(root);
  });
  afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

  it("takes modules from the .readynative.json selection, skipping none/empty", () => {
    expect(ids(graph)).toContain("module:ui/nativewind5");
    expect(ids(graph)).toContain("module:data/react-query");
    expect(ids(graph)).not.toContain("module:auth/none");
    expect(ids(graph)).not.toContain("module:payments/");
  });

  it("makes a service node out of a module's doctor env checks", () => {
    expect(ids(graph)).toContain("service:react-query");
    expect(graph.nodes.find((n) => n.id === "service:react-query")?.label).toBe("React Query");
    expect(has(graph, "module:data/react-query", "configures", "service:react-query")).toBe(true);
    expect(has(graph, "service:react-query", "reads", "env:API_SECRET")).toBe(true);
    expect(graph.nodes.find((n) => n.id === "service:react-query")?.meta).toEqual({
      env: ["API_SECRET", "EXPO_PUBLIC_API_URL"],
      guide: "https://readynative.app/docs/features/data/react-query",
    });
  });

  it("makes one env node per key, comments excluded", () => {
    const env = graph.nodes.filter((n) => n.kind === "env").map((n) => n.id);
    expect(env).toEqual([
      "env:API_SECRET",
      "env:EXPO_PUBLIC_API_URL",
      "env:EXPO_PUBLIC_APP_VARIANT",
    ]);
  });

  it("walks src/app into routes and skips private files", () => {
    const routes = graph.nodes.filter((n) => n.kind === "route").map((n) => n.id);
    expect(routes.slice().sort()).toEqual([
      "route:(tabs)/_layout",
      "route:/",
      "route:/api/hello",
      "route:/entry/[id]",
      "route:_layout",
    ]);
  });

  it("links providers in composition order and back to the module that provides them", () => {
    expect(has(graph, "provider:QueryProvider", "renders", "provider:UiThemeProvider")).toBe(true);
    expect(has(graph, "provider:QueryProvider", "imports", "lib:query")).toBe(true);
    expect(has(graph, "module:data/react-query", "provides", "provider:QueryProvider")).toBe(true);
  });

  it("reads imports, renders and env reads off the sources", () => {
    expect(has(graph, "lib:api/client", "imports", "lib:env")).toBe(true);
    expect(has(graph, "lib:api/client", "reads", "env:EXPO_PUBLIC_API_URL")).toBe(true);
    expect(has(graph, "route:/", "renders", "screen:home/home-screen")).toBe(true);
    expect(has(graph, "hook:use-thing", "imports", "store:thing")).toBe(true);
    // A route importing a lib is an import, not a render.
    expect(has(graph, "route:/", "imports", "screen:home/home-screen")).toBe(false);
  });

  it("ignores test files", () => {
    expect(ids(graph)).not.toContain("screen:__tests__/home-screen.test");
  });

  it("picks up // @graph annotations where they were written", () => {
    const node = graph.nodes.find((n) => n.id === "custom:sync");
    expect(node).toMatchObject({
      kind: "feature",
      label: "Background sync",
      file: "src/screens/home/home-screen.tsx",
    });
    expect(has(graph, "custom:sync", "custom", "lib:api/client")).toBe(true);
  });

  it("merges docs/graph.extra.json verbatim", () => {
    expect(ids(graph)).toContain("service:stripe");
    expect(has(graph, "service:stripe", "reads", "env:EXPO_PUBLIC_API_URL")).toBe(true);
  });

  it("reports a dangling endpoint as a warning, not an error", () => {
    expect(validateGraph(graph)).toEqual([
      `edge service:stripe -custom-> nope:missing: no node "nope:missing"`,
    ]);
  });

  it("is deterministic: two builds of the same tree are identical", () => {
    expect(JSON.stringify(buildGraph(root))).toBe(JSON.stringify(graph));
    expect(graph.generatedAt).toBeUndefined();
  });

  it("falls back to modules/** before setup", () => {
    fs.rmSync(path.join(root, ".readynative.json"));
    fs.mkdirSync(path.join(root, "modules/auth/supabase"), { recursive: true });
    fs.writeFileSync(
      path.join(root, "modules/auth/supabase/module.json"),
      JSON.stringify({ id: "supabase", category: "auth", label: "Supabase", guide: "/docs/x" })
    );
    fs.mkdirSync(path.join(root, "modules/auth/none"), { recursive: true });
    const before = buildGraph(root);
    expect(ids(before)).toContain("module:auth/supabase");
    expect(ids(before)).not.toContain("module:auth/none");
    expect(before.nodes.find((n) => n.id === "module:auth/supabase")?.label).toBe("auth: Supabase");
  });
});

describe("rendering", () => {
  let root: string;
  beforeEach(() => {
    root = createTree();
  });
  afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

  it("renders a mermaid flowchart grouped by kind, with sanitized ids", () => {
    const mermaid = renderMermaid(buildGraph(root));
    expect(mermaid.startsWith("flowchart LR")).toBe(true);
    expect(mermaid).toContain(`subgraph routes["route"]`);
    expect(mermaid).toContain(`nroute__entry__id_["/entry/[id]"]`);
    expect(mermaid).toContain("-->|renders| nscreen_home_home_screen");
    // Dangling edges are dropped from the picture; validateGraph is where they surface.
    expect(mermaid).not.toContain("nope_missing");
  });

  it("renders ARCHITECTURE.md with the header, Start here and a table per kind", () => {
    const md = renderArchitecture(buildGraph(root));
    expect(md).toContain("Generated by `bun run gen:graph` - do not edit");
    expect(md).toContain("## Start here");
    expect(md).toContain("```mermaid");
    expect(md).toContain("## route (5)");
    expect(md).toContain("| `lib:env` | @/lib/env | `src/lib/env.ts` |");
  });
});

describe("writeGraph / checkGraph", () => {
  let root: string;
  beforeEach(() => {
    root = createTree();
  });
  afterEach(() => fs.rmSync(root, { recursive: true, force: true }));

  it("writes both files, then has nothing to write on a second run", async () => {
    expect(await writeGraph(root)).toEqual([GRAPH_JSON, ARCHITECTURE_MD]);
    const before = fs.readFileSync(path.join(root, GRAPH_JSON), "utf8");
    expect(await writeGraph(root)).toEqual([]);
    expect(fs.readFileSync(path.join(root, GRAPH_JSON), "utf8")).toBe(before);
  });

  it("routes both files through an injected writer", async () => {
    const seen: string[] = [];
    await writeGraph(root, (rel) => seen.push(rel));
    expect(seen).toEqual([GRAPH_JSON, ARCHITECTURE_MD]);
    expect(fs.existsSync(path.join(root, GRAPH_JSON))).toBe(false);
  });

  it("reports drift until the files are regenerated", async () => {
    expect(await checkGraph(root)).toEqual([GRAPH_JSON, ARCHITECTURE_MD]);
    await writeGraph(root);
    expect(await checkGraph(root)).toEqual([]);

    fs.mkdirSync(path.join(root, "src/app/new"), { recursive: true });
    fs.writeFileSync(path.join(root, "src/app/new/index.tsx"), "export default function N() {}\n");
    expect(await checkGraph(root)).toEqual([GRAPH_JSON, ARCHITECTURE_MD]);
  });
});
