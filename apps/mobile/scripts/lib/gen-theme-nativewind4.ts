/**
 * tokens → `src/global.css` + `tailwind.config.js` for nativewind4.
 *
 * NativeWind 4 / Tailwind 3 keep colours as bare HSL triples (`--primary: 0 0% 9%`)
 * so `bg-primary/90` can wrap them in `hsl(var(--primary) / 0.9)`. Both files
 * are derived from the same `ThemeInput` as the nativewind5 generator (hex
 * `--color-*` records); the hex → HSL conversion happens here.
 */
import type { ThemeInput } from "./gen-theme.ts";

export const NATIVEWIND4_MODULE_CSS = "modules/ui/nativewind4/files/src/global.css";
export const NATIVEWIND4_MODULE_TAILWIND = "modules/ui/nativewind4/files/tailwind.config.js";
export const NATIVEWIND4_ROOT_TAILWIND = "tailwind.config.js";

interface Hsl {
  h: number;
  s: number;
  l: number;
  /** 0..1 when the input had an alpha channel (`#rrggbbaa`), else undefined. */
  alpha?: number;
}

function fmt(n: number): string {
  // One decimal like shadcn (`0 0% 3.9%`), trailing `.0` dropped.
  return (Math.round(n * 10) / 10).toString();
}

/** `#rgb`, `#rrggbb`, `#rrggbbaa` → HSL. Throws on anything else (tokens are hex-only). */
export function hexToHsl(hex: string): Hsl {
  const raw = hex.trim().replace(/^#/, "");
  let digits = raw;
  if (raw.length === 3 || raw.length === 4) {
    digits = raw
      .split("")
      .map((c) => c + c)
      .join("");
  }
  if (!/^[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$/.test(digits)) {
    throw new Error(`gen-theme-nativewind4: expected a hex colour, got "${hex}"`);
  }
  const r = parseInt(digits.slice(0, 2), 16) / 255;
  const g = parseInt(digits.slice(2, 4), 16) / 255;
  const b = parseInt(digits.slice(4, 6), 16) / 255;
  const alpha = digits.length === 8 ? parseInt(digits.slice(6, 8), 16) / 255 : undefined;

  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let h = 0;
  let s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60;
  }
  return { h, s: s * 100, l: l * 100, alpha };
}

/** `#171717` → `0 0% 9%` (the `H S% L%` triple NativeWind 4 configs expect). */
export function hexToHslTriple(hex: string): string {
  const { h, s, l } = hexToHsl(hex);
  return `${fmt(h)} ${fmt(s)}% ${fmt(l)}%`;
}

/** `--color-card-foreground` → `--card-foreground`. */
function shortVar(name: string): string {
  return name.replace(/^--color-/, "--");
}

/** `--card-foreground` → `card-foreground` (Tailwind colour key). */
function colorKey(name: string): string {
  return name.replace(/^--/, "");
}

/** Alpha-composite `#rrggbbaa` onto an opaque `#rrggbb` backdrop → `#rrggbb`. */
function flattenAlpha(hex: string, backdrop: string): string {
  const fg = hex.replace(/^#/, "");
  const bg = backdrop.replace(/^#/, "");
  const a = parseInt(fg.slice(6, 8), 16) / 255;
  const channel = (i: number) => {
    const f = parseInt(fg.slice(i, i + 2), 16);
    const b = parseInt(bg.slice(i, i + 2), 16);
    return Math.round(f * a + b * (1 - a))
      .toString(16)
      .padStart(2, "0");
  };
  return `#${channel(0)}${channel(2)}${channel(4)}`;
}

function hslVars(record: Record<string, string>, indent: string): string {
  const backdrop = record["--color-background"];
  return Object.entries(record)
    .map(([name, hex]) => {
      let value = hex;
      let note = "";
      if (hexToHsl(hex).alpha !== undefined) {
        // HSL triples cannot carry alpha. Flatten onto the mode's background when
        // we know it (visually equivalent on flat surfaces), otherwise drop the
        // alpha and say so.
        if (backdrop && hexToHsl(backdrop).alpha === undefined) {
          value = flattenAlpha(hex.replace(/^#/, "").length === 4 ? expand(hex) : hex, backdrop);
          note = ` /* ${hex} flattened onto ${backdrop} */`;
        } else {
          note = ` /* alpha dropped from ${hex} */`;
        }
      }
      return `${indent}${shortVar(name)}: ${hexToHslTriple(value)};${note}`;
    })
    .join("\n");
}

/** `#rgba` → `#rrggbbaa`. */
function expand(hex: string): string {
  return `#${hex
    .replace(/^#/, "")
    .split("")
    .map((c) => c + c)
    .join("")}`;
}

export function renderNativewind4Css(input: ThemeInput): string {
  return `@tailwind base;
@tailwind components;
@tailwind utilities;

/* Generated by \`bun gen:theme\` from src/theme/tokens.ts - edit tokens, not this file. */
@layer base {
  :root {
${hslVars(input.light, "    ")}
    --radius: ${input.radius.lg}px;
    --radius-md: ${input.radius.md}px;
    --radius-sm: ${input.radius.sm}px;
  }

  /* \`darkMode: "class"\`: applied when NativeWind's colorScheme is dark. */
  .dark:root {
${hslVars(input.dark, "    ")}
  }
}
`;
}

/**
 * Tailwind colour entries. `x` + `x-foreground` pairs nest as
 * `{ DEFAULT, foreground }` (RNR convention); everything else is flat.
 */
function tailwindColors(vars: string[]): string {
  const keys = vars.map(colorKey);
  const set = new Set(keys);
  const lines: string[] = [];
  const done = new Set<string>();
  const value = (key: string) => `"hsl(var(--${key}) / <alpha-value>)"`;
  for (const key of keys) {
    if (done.has(key)) continue;
    const fg = `${key}-foreground`;
    if (set.has(fg)) {
      lines.push(`        ${key}: {`);
      lines.push(`          DEFAULT: ${value(key)},`);
      lines.push(`          foreground: ${value(fg)},`);
      lines.push(`        },`);
      done.add(key);
      done.add(fg);
    } else if (!key.endsWith("-foreground") || !set.has(key.replace(/-foreground$/, ""))) {
      const prop = /^[a-z][a-z0-9]*$/i.test(key) ? key : `"${key}"`;
      lines.push(`        ${prop}: ${value(key)},`);
      done.add(key);
    }
  }
  return lines.join("\n");
}

export function renderNativewind4TailwindConfig(input: ThemeInput): string {
  const vars = Object.keys(input.light).map(shortVar);
  return `// Generated by \`bun gen:theme\` from src/theme/tokens.ts - edit tokens, not this file.
const { hairlineWidth } = require("nativewind/theme");

/** @type {import('tailwindcss').Config} */
module.exports = {
  darkMode: "class",
  content: ["./src/**/*.{ts,tsx}"],
  presets: [require("nativewind/preset")],
  theme: {
    extend: {
      colors: {
${tailwindColors(vars)}
      },
      borderRadius: {
        lg: "var(--radius)",
        md: "var(--radius-md)",
        sm: "var(--radius-sm)",
      },
      borderWidth: {
        hairline: hairlineWidth(),
      },
    },
  },
  future: {
    hoverOnlyWhenSupported: true,
  },
  plugins: [require("tailwindcss-animate")],
};
`;
}

/** Both nativewind4 artefacts for one input, keyed by root-relative module path. */
export function renderNativewind4(input: ThemeInput): Record<string, string> {
  return {
    [NATIVEWIND4_MODULE_CSS]: renderNativewind4Css(input),
    [NATIVEWIND4_MODULE_TAILWIND]: renderNativewind4TailwindConfig(input),
  };
}
